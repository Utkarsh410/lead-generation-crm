#!/usr/bin/env node
// Generates src/lib/supabase/database.types.ts from a live Postgres schema.
// Usage: DATABASE_URL=postgres://… node scripts/gen-db-types.mjs
// (Equivalent to `supabase gen types typescript`, without needing Docker.
// TEXT columns with `col IN (…)` CHECK constraints become string-literal unions.)

import { writeFileSync } from "node:fs";
import pg from "pg";

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("Set DATABASE_URL");
  process.exit(1);
}

const client = new pg.Client({ connectionString: url });
await client.connect();

const { rows: columns } = await client.query(`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable, c.column_default,
         c.is_generated, c.ordinal_position
    from information_schema.columns c
    join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
   where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
   order by c.table_name, c.ordinal_position`);

const { rows: checks } = await client.query(`
  select rel.relname as table_name, pg_get_constraintdef(con.oid) as def
    from pg_constraint con
    join pg_class rel on rel.oid = con.conrelid
    join pg_namespace n on n.oid = rel.relnamespace
   where n.nspname = 'public' and con.contype = 'c'`);

const { rows: fks } = await client.query(`
  select con.conname, rel.relname as table_name, frel.relname as foreign_table,
         array(select a.attname from unnest(con.conkey) k join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k)::text[] as cols,
         array(select a.attname from unnest(con.confkey) k join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k)::text[] as fcols,
         exists (
           select 1 from pg_index i
            where i.indrelid = con.conrelid and i.indisunique
              and (i.indkey::int2[])::int[] @> con.conkey::int[] and array_length(i.indkey::int2[], 1) = array_length(con.conkey, 1)
         ) as one_to_one
    from pg_constraint con
    join pg_class rel on rel.oid = con.conrelid
    join pg_class frel on frel.oid = con.confrelid
    join pg_namespace n on n.oid = rel.relnamespace
    join pg_namespace fn on fn.oid = frel.relnamespace
   where n.nspname = 'public' and fn.nspname = 'public' and con.contype = 'f'
   order by con.conname`);

const { rows: fns } = await client.query(`
  select p.proname, pg_get_function_result(p.oid) as result
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.pronargs = 0 and pg_get_function_result(p.oid) = 'boolean'
   order by p.proname`);

await client.end();

// enum-like CHECK constraints: (col = ANY (ARRAY['a'::text, 'b'::text]))
const enums = {};
for (const { table_name, def } of checks) {
  const re = /\(?(\w+) = ANY \(+ARRAY\[([^\]]+)\]\)+/g;
  let m;
  while ((m = re.exec(def))) {
    const values = [...m[2].matchAll(/'((?:[^']|'')*)'::text/g)].map((v) => v[1].replace(/''/g, "'"));
    if (values.length) enums[`${table_name}.${m[1]}`] = values;
  }
}

function tsType(col, mode) {
  const e = enums[`${col.table_name}.${col.column_name}`];
  if (e) return e.map((v) => JSON.stringify(v)).join(" | ");
  switch (col.udt_name) {
    case "uuid":
    case "text":
    case "varchar":
    case "date":
    case "time":
    case "timestamptz":
    case "timestamp":
      return "string";
    case "int2":
    case "int4":
    case "int8":
    case "float4":
    case "float8":
      return "number";
    case "numeric":
      return mode === "Row" ? "number" : "number | string";
    case "bool":
      return "boolean";
    case "json":
    case "jsonb":
      return "Json";
    case "_text":
      return "string[]";
    default:
      return "unknown";
  }
}

const tables = {};
for (const col of columns) (tables[col.table_name] ??= []).push(col);

let out = `// Generated by scripts/gen-db-types.mjs — do not edit by hand.\n\n`;
out += `export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\n`;
out += `export type Database = {\n  public: {\n    Tables: {\n`;
for (const [table, cols] of Object.entries(tables)) {
  out += `      ${table}: {\n`;
  for (const mode of ["Row", "Insert", "Update"]) {
    out += `        ${mode}: {\n`;
    for (const col of cols) {
      if (mode !== "Row" && col.is_generated === "ALWAYS") continue;
      const nullable = col.is_nullable === "YES";
      const optional = mode === "Update" || (mode === "Insert" && (nullable || col.column_default !== null));
      const type = tsType(col, mode) + (nullable ? " | null" : "");
      out += `          ${col.column_name}${optional ? "?" : ""}: ${type};\n`;
    }
    out += `        };\n`;
  }
  out += `        Relationships: [\n`;
  for (const fk of fks.filter((f) => f.table_name === table)) {
    out += `          {\n            foreignKeyName: ${JSON.stringify(fk.conname)};\n            columns: ${JSON.stringify(fk.cols)};\n            isOneToOne: ${fk.one_to_one};\n            referencedRelation: ${JSON.stringify(fk.foreign_table)};\n            referencedColumns: ${JSON.stringify(fk.fcols)};\n          },\n`;
  }
  out += `        ];\n      };\n`;
}
out += `    };\n    Views: { [_ in never]: never };\n    Functions: {\n`;
for (const fn of fns) out += `      ${fn.proname}: { Args: Record<PropertyKey, never>; Returns: boolean };\n`;
out += `    };\n    Enums: { [_ in never]: never };\n    CompositeTypes: { [_ in never]: never };\n  };\n};\n\n`;
out += `type PublicTables = Database["public"]["Tables"];\n`;
out += `export type Tables<T extends keyof PublicTables> = PublicTables[T]["Row"];\n`;
out += `export type TablesInsert<T extends keyof PublicTables> = PublicTables[T]["Insert"];\n`;
out += `export type TablesUpdate<T extends keyof PublicTables> = PublicTables[T]["Update"];\n`;

const target = new URL("../src/lib/supabase/database.types.ts", import.meta.url);
writeFileSync(target, out);
console.log(`Wrote ${Object.keys(tables).length} tables to ${target.pathname}`);
